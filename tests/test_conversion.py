def test_projection_matches_analytic_rays():
    # Source channels encode longitude and latitude, so inverse mapping can
    # be checked independently at off-centre output locations.
    n=1024
    x=np.tile(np.linspace(0,255,n,dtype=np.float32),(n,1))
    src=np.stack((x,x.T,np.zeros_like(x)),axis=-1)
    out=project(src,401,301,75)
    f=401/(2*math.tan(math.radians(75)/2))
    for row,col in [(150,200),(30,50),(270,350)]:
        rx,ry=(col+.5-401/2)/f,(row+.5-301/2)/f
        lon=math.atan2(rx,1)
        lat=math.atan2(ry,math.sqrt(1+rx*rx))
        expected=np.array([(lon/math.pi+.5)*n-.5,(lat/math.pi+.5)*n-.5])*255/(n-1)
        assert np.allclose(out[row,col,:2],expected,atol=.04)


def test_pitch_selects_lower_latitude_and_preserves_horizontal_epipolar_lines():
    n=1024
    ramp=np.tile(np.linspace(0,255,n,dtype=np.float32),(n,1))
    src=np.stack((ramp,ramp.T,np.zeros_like(ramp)),axis=-1)
    out=project(src,401,301,75,30)
    expected_y=((.5+30/180)*n-.5)*255/(n-1)
    assert out[150,200,1]==pytest.approx(expected_y,abs=.04)
    # Rotating the coordinate system around baseline x leaves y/z identical
    # for corresponding points in parallel left and right pinhole cameras.
    angle=math.radians(30)
    for x,y,z in [(0,.7,1),(1,.5,2),(-.3,1.2,3)]:
        projected=[]
        for camera_x in [0,.06]:
            yr=math.cos(angle)*y-math.sin(angle)*z
            zr=math.sin(angle)*y+math.cos(angle)*z
            projected.append(((x-camera_x)/zr,yr/zr))
        assert projected[0][1]==projected[1][1]
        assert projected[0][0]>projected[1][0]
    with pytest.raises(ValueError,match='hemisphere'):
        project(src,401,401,88,60)


@pytest.mark.parametrize('fov,baseline,disparity',[(75,60,.02),(30,19.2,-.015),(85,64,0)])
def test_native_decoder_and_metadata(tmp_path,fov,baseline,disparity):
    path=tmp_path/'测试 spatial.heic'
    save_spatial(Image.new('RGB',(128,96),'red'),Image.new('RGB',(128,96),'blue'),
                 path,fov,baseline,disparity)
    report=inspect_spatial(path)
    assert report['baseline_mm']==baseline
    assert report['cameras'][0]['hfov']==pytest.approx(fov,abs=1e-5)
    assert report['cameras'][1]['disparity']==disparity
    decoded=pillow_heif.open_heif(path)
    l,r=np.asarray(decoded[0]),np.asarray(decoded[1])
    assert l[:,:,0].mean()>245 and l[:,:,2].mean()<10
    assert r[:,:,2].mean()>245 and r[:,:,0].mean()<10
    assert decoded.info['primary']
    assert report['native_libheif']['chroma']==420


def test_original_media_offsets_unchanged():
    h=pillow_heif.from_pillow(Image.new('RGB',(64,64),'red'))
    h.add_from_pillow(Image.new('RGB',(64,64),'blue'))
    buf=io.BytesIO(); h.save(buf,quality=80)
    original=buf.getvalue()
    result=package_stereo(original,75,60,.02)
    om=[(raw,offset) for k,p,raw,offset in boxes(original) if k==b'mdat']
    nm=[(raw,offset) for k,p,raw,offset in boxes(result) if k==b'mdat']
    assert om==nm


def test_apple_reference_property_layout(tmp_path):
    # Known ImageIO UUID payload encodings, obtained from public reference
    # udibr/fisheye examples/0S9A9186.heic, not generated by this writer.
    ref_intrinsic=bytes.fromhex('00001e000a65be2b2000000020000000')
    flags,fx,cx,cy=struct.unpack('>Iiii',ref_intrinsic)
    assert flags==30<<8 and cx/2**30==.5 and cy/2**30==.5
    assert bytes.fromhex('000000110000ea60')==struct.pack('>Ii',0x11,60000)
    path=tmp_path/'test.heic'
    fov=math.degrees(2*math.atan(.5/(fx/2**30)))
    save_spatial(Image.new('RGB',(64,64)),Image.new('RGB',(64,64)),path,fov,60,-.1)
    meta=child(path.read_bytes(),b'meta')
    properties=list(boxes(child(child(meta[4:],b'iprp'),b'ipco')))
    uuids={p[:16]:[] for k,p,_,_ in properties if k==b'uuid'}
    for k,p,_,_ in properties:
        if k==b'uuid': uuids[p[:16]].append(p[16:])
    assert ref_intrinsic in uuids[INTRINSICS]
    assert bytes.fromhex('000000110000ea60') in uuids[EXTRINSICS]
    assert bytes.fromhex('fffffc18') in uuids[DISPARITY]


